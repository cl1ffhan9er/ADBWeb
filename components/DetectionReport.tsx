"use client";

import { useState } from "react";
import { formatScore, getBandDetails, type ScoreTone } from "@/lib/scoreBands";
import ScoreExplainerDialog from "@/components/ScoreExplainerDialog";

type ChunkResult = {
  chunk_index: number;
  label: string;
  score: number;
  raw_score?: number;
  start_s?: number;
  end_s?: number;
};

type DetectionReportProps = {
  result: {
    filename: string;
    duration_seconds: number;
    overall_label: string;
    overall_score: number;
    overall_raw_score?: number;
    threshold?: number;
    chunks?: ChunkResult[];
  };
  fileSizeBytes?: number;
};

const DISCLAIMER =
  "This result is generated by a machine learning model and should not be used as sole evidence for " +
  "forensic investigations, legal proceedings, or other high-stakes decisions.";

const TONE_STYLES: Record<ScoreTone, { iconBox: string; text: string; badge: string }> = {
  real: { iconBox: "bg-green-200 text-green-800", text: "text-green-800", badge: "bg-green-200 text-green-900" },
  uncertain: { iconBox: "bg-amber-100 text-amber-700", text: "text-amber-800", badge: "bg-amber-100 text-amber-900" },
  fake: { iconBox: "bg-red-300 text-red-900", text: "text-red-800", badge: "bg-red-300 text-red-900" },
};

function formatDuration(seconds: number) {
  const total = Math.round(seconds);
  const m = Math.floor(total / 60);
  const s = total % 60;
  return `${m}:${s.toString().padStart(2, "0")}`;
}

function formatFileSize(bytes?: number) {
  if (bytes === undefined) return "—";
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

function formatExtension(filename: string) {
  const match = /\.([a-z0-9]+)$/i.exec(filename);
  return match ? `.${match[1].toUpperCase()}` : "—";
}

function VerdictIcon({ tone }: { tone: ScoreTone }) {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" className="size-8" aria-hidden="true">
      <circle cx="12" cy="12" r="9" />
      {tone === "real" ? (
        <path d="M8 12.5l2.5 2.5L16 9.5" strokeLinecap="round" strokeLinejoin="round" />
      ) : tone === "fake" ? (
        <path d="M9 9l6 6M15 9l-6 6" strokeLinecap="round" />
      ) : (
        <path d="M9.75 9.5a2.25 2.25 0 1 1 3.2 2.04c-.6.28-.95.84-.95 1.46v.5M12 16.5h.01" strokeLinecap="round" />
      )}
    </svg>
  );
}

function InfoIcon() {
  return (
    <svg viewBox="0 0 20 20" fill="currentColor" className="size-3.5" aria-hidden="true">
      <path
        fillRule="evenodd"
        d="M18 10a8 8 0 1 1-16 0 8 8 0 0 1 16 0Zm-7-4a1 1 0 1 1-2 0 1 1 0 0 1 2 0ZM9 9a.75.75 0 0 0 0 1.5h.253a.25.25 0 0 1 .244.304l-.459 2.066A1.75 1.75 0 0 0 10.747 15H11a.75.75 0 0 0 0-1.5h-.253a.25.25 0 0 1-.244-.304l.459-2.066A1.75 1.75 0 0 0 9.253 9H9Z"
        clipRule="evenodd"
      />
    </svg>
  );
}

function Field({ label, value, title }: { label: string; value: string; title?: string }) {
  return (
    <div className="min-w-0 rounded-xl bg-slate-100 px-3 py-2">
      <dt className="text-[11px] text-slate-500">{label}</dt>
      <dd className="truncate text-sm font-semibold text-slate-900" title={title}>
        {value}
      </dd>
    </div>
  );
}

const TIMELINE_COLORS: Record<ScoreTone, string> = {
  real: "bg-green-400",
  uncertain: "bg-amber-300",
  fake: "bg-red-400",
};

function formatRange(chunk: ChunkResult) {
  if (chunk.start_s === undefined || chunk.end_s === undefined) return "";
  return `${chunk.start_s.toFixed(1)}–${chunk.end_s.toFixed(1)} s`;
}

function SegmentAnalysis({ chunks }: { chunks: ChunkResult[] }) {
  const [showDetails, setShowDetails] = useState(false);
  const flagged = chunks.filter((c) => c.label === "spoof").length;
  const summary = `${chunks.length} segments · ${flagged} flagged as fake`;

  return (
    <div>
      <div className="mb-1.5 flex items-center justify-between gap-2 text-xs">
        <p className="min-w-0 truncate font-medium text-slate-500">
          Segment analysis <span className="font-normal text-slate-400">· {summary}</span>
        </p>
        <button
          type="button"
          onClick={() => setShowDetails((v) => !v)}
          aria-expanded={showDetails}
          className="shrink-0 font-medium text-adb-500 hover:underline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-adb-500"
        >
          {showDetails ? "Hide details" : "Show details"}
        </button>
      </div>

      <div className="flex h-3 w-full gap-0.5 overflow-hidden rounded-full" role="img" aria-label={summary}>
        {chunks.map((chunk) => {
          const band = getBandDetails(chunk.score);
          const seconds =
            chunk.start_s !== undefined && chunk.end_s !== undefined ? Math.max(chunk.end_s - chunk.start_s, 0.1) : 1;
          return (
            <div
              key={chunk.chunk_index}
              className={TIMELINE_COLORS[band.tone]}
              style={{ flexGrow: seconds, flexBasis: 0 }}
              title={`Segment ${chunk.chunk_index + 1} (${formatRange(chunk)}): ${band.label}, ${formatScore(chunk.score)}`}
            />
          );
        })}
      </div>

      {showDetails ? (
        <ul className="mt-2 max-h-40 divide-y divide-slate-100 overflow-y-auto rounded-xl border border-slate-100 text-xs">
          {chunks.map((chunk) => {
            const band = getBandDetails(chunk.score);
            return (
              <li key={chunk.chunk_index} className="flex items-center gap-2 px-3 py-1.5">
                <span className="w-7 shrink-0 tabular-nums text-slate-700">#{chunk.chunk_index + 1}</span>
                <span className="w-24 shrink-0 tabular-nums text-slate-400">{formatRange(chunk)}</span>
                <span className={`min-w-0 truncate rounded-full px-2 py-0.5 font-medium ${band.colorClass}`}>
                  {band.label}
                </span>
                <span className="ml-auto shrink-0 tabular-nums text-slate-500">{formatScore(chunk.score)}</span>
              </li>
            );
          })}
        </ul>
      ) : null}
    </div>
  );
}

export default function DetectionReport({ result, fileSizeBytes }: DetectionReportProps) {
  const [showExplainer, setShowExplainer] = useState(false);
  const band = getBandDetails(result.overall_score);
  const tone = TONE_STYLES[band.tone];
  const score = formatScore(result.overall_score);
  const hasChunks = !!result.chunks && result.chunks.length > 1;

  return (
    <section className="p-5 sm:p-6">
      <h2 id="detection-report-title" className="pr-10 text-2xl font-bold tracking-wide text-adb-500">
        DETECTION REPORT
      </h2>

      <div className="mt-4 space-y-4 rounded-2xl border border-slate-100 p-4 shadow-sm sm:p-5">
        <div className="flex items-center gap-4">
          <div className={`flex size-14 shrink-0 items-center justify-center rounded-xl ${tone.iconBox}`}>
            <VerdictIcon tone={band.tone} />
          </div>
          <div className="min-w-0">
            <p className={`text-xl font-extrabold uppercase leading-tight sm:text-2xl ${tone.text}`}>{band.label}</p>
            <p className={`text-sm ${tone.text}`}>{band.description}</p>
          </div>
        </div>

        <div className="flex items-center justify-between gap-4">
          <div>
            <p className="font-semibold text-adb-500">Authenticity Score</p>
            <button
              type="button"
              onClick={() => setShowExplainer(true)}
              className="inline-flex items-center gap-1 text-xs text-slate-400 transition-colors hover:text-adb-500 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-adb-500"
            >
              <InfoIcon />
              What is Authenticity Score?
            </button>
          </div>
          <span
            className={`min-w-12 rounded-lg px-3 py-1 text-center text-xl font-bold tabular-nums ${tone.badge}`}
            aria-label={`Authenticity score ${score} out of 100`}
          >
            {score}
          </span>
        </div>

        <dl className="grid grid-cols-2 gap-3">
          <Field label="File Name" value={result.filename} title={result.filename} />
          <Field label="File Size" value={formatFileSize(fileSizeBytes)} />
          <Field label="Duration" value={formatDuration(result.duration_seconds)} />
          <Field label="Format" value={formatExtension(result.filename)} />
        </dl>

        {hasChunks ? <SegmentAnalysis chunks={result.chunks!} /> : null}

        <p className="rounded-xl bg-slate-100 px-3 py-2 text-[11px] leading-snug text-slate-500">{DISCLAIMER}</p>
      </div>

      {showExplainer ? <ScoreExplainerDialog onClose={() => setShowExplainer(false)} /> : null}
    </section>
  );
}
